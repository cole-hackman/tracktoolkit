/** "2026-09-22" → "22 September 2026". Pure string work, no Date parsing. */
function formatIsoDate(iso: string): string {
  const [year, month, day] = iso.split("-");
  return `${Number(day)} ${MONTHS[Number(month) - 1]} ${year}`;
}

/**
 * Horizontal scroll container for a table too wide for a phone.
 *
 * `tabIndex={0}` is required, not decorative: WCAG 2.1.1 — and axe's
 * `scrollable-region-focusable` check, which the e2e suite runs against this
 * page — says a region that scrolls has to be reachable by keyboard, and a
 * plain `div` is not. The jsx-a11y rule that flags a tabbable non-interactive
 * element allows only `tabpanel`, so it is switched off here by name.
 */
function ScrollableTable({
  label,
  children,
}: {
  label: string;
  children: React.ReactNode;
}) {
  return (
    // eslint-disable-next-line jsx-a11y/no-noninteractive-tabindex
    <div className="overflow-x-auto" tabIndex={0} role="region" aria-label={label}>
      {children}
    </div>
  );
}

